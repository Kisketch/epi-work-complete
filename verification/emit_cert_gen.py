"""Generic emitter (2026-11-23): all 20 N=512 residue certificates -> kernel-checkable core Lean.

For each (m, r) in residue_certificate_general_N512.json and each side (lower / upper) this
writes, under epi_formal/EpiFormal/ResidueCertGen/:
  <Tag>.lean        parameters, vector, `vec_ok`, `tail_ok`        (Tag = M<m>R<r><L|U>)
  <Tag>C<c>.lean    rows [64c, 64c+64) and `ok<c>` for c = 0..7
  <Tag>All.lean     imports the chunks; `tab`, `tab_length`, `tab_ok`
using the checkers of EpiFormal/ResidueCertGenBase.lean. Every Lean check is first mirrored
in exact Python integer arithmetic below (assertions), and the minimal row margin is
compared with `certify_side` of residue_certificate_general_N512.py (must be equal).

Usage: python verification/emit_cert_gen.py [Tag ...]     (default: all 20)
"""
import json
import sys
from fractions import Fraction
from pathlib import Path

import residue_certificate_general_N512 as cert

HERE = Path(__file__).resolve().parent
DST = HERE.parent / "epi_formal" / "EpiFormal" / "ResidueCertGen"
N, SCALE, KMAX = cert.GRID, cert.SCALE, cert.FINITE_DIGITS
CH = 64  # rows per chunk


def cellAt(a, e):
    return min(N - 1, N * N // (a * N + e))


def lst(xs):
    return "[" + ", ".join(str(int(x)) for x in xs) + "]"


def build(m, r, side, s):
    rows, lower_tail, upper_tail, K = cert.coefficients(m, r, s)
    v = cert.provisional_vector(rows, (lower_tail + upper_tail) // 2)
    two_s = 2 * s
    p, q = two_s.numerator, two_s.denominator
    assert p > q >= 1 and len(v) == N
    assert all(v[i] >= v[i + 1] for i in range(N - 1)) and min(v) >= 1
    assert N + 1 <= m * K + r
    coef, margins = [], []
    for j, row in enumerate(rows):
        assert len(row) == K
        cs, tot = [], 0
        for k, (lo, hi, left, right) in enumerate(row):
            a = m * k + r
            assert left == cellAt(a, j + 1) and right == cellAt(a, j) and left <= right
            if side == "upper":
                assert SCALE**q * N**p <= hi**q * (a * N + j) ** p
                assert max(v[left:right + 1]) == v[left]
                cs.append(hi)
                tot += hi * v[left]
            else:
                assert lo**q * (a * N + j + 1) ** p <= SCALE**q * N**p
                assert min(v[left:right + 1]) == v[right]
                cs.append(lo)
                tot += lo * v[right]
        bound = SCALE * v[j]
        if side == "upper":
            assert tot + upper_tail * v[0] < bound
            margins.append(Fraction(bound - tot - upper_tail * v[0], bound))
        else:
            assert bound < tot + lower_tail * v[0]
            margins.append(Fraction(tot + lower_tail * v[0] - bound, bound))
        coef.append(cs)
    ref, _ = cert.certify_side(m, r, s, side)
    assert min(margins) == ref, (m, r, side, min(margins), ref)
    alpha = two_s - 1
    if side == "upper":
        _, u = cert.enclose_power(Fraction(m * (K - 1) + r), alpha)
        assert SCALE**q <= u**q * (m * (K - 1) + r) ** (p - q) and u * q <= upper_tail * m * (p - q)
        tail = dict(tail=upper_tail, u=u)
    else:
        l, _ = cert.enclose_power(Fraction(m * K + r + 1), alpha)
        _, u = cert.enclose_power(Fraction(m * KMAX + r + 1), alpha)
        assert l**q * (m * K + r + 1) ** (p - q) <= SCALE**q
        assert SCALE**q <= u**q * (m * KMAX + r + 1) ** (p - q)
        assert lower_tail * m * (p - q) + u * q <= l * q
        tail = dict(tail=lower_tail, l=l, u=u)
    cert.enclose_power.cache_clear()
    return dict(K=K, p=p, q=q, v=v, coef=coef, margin=min(margins), **tail)


def emit(tag, m, r, side, s, d):
    DST.mkdir(parents=True, exist_ok=True)
    ns = f"ResidueCertGen.{tag}"
    hdr = (f"-- GENERATED by verification/emit_cert_gen.py: N={N}, m={m}, r={r}, {side} side, "
           f"s={s} (2s = {d['p']}/{d['q']}). Kernel-checked data; soundness in ResidueCertGenSound.")
    chk = "allU" if side == "upper" else "allL"
    A = f"vec {N} {m} {r} {d['K']} {d['p']} {d['q']} {SCALE} tail"
    L = [hdr, "import EpiFormal.ResidueCertGenBase", "", "set_option maxRecDepth 100000", "",
         f"namespace {ns}", "open ResidueCertGen", "",
         f"def m : Nat := {m}", f"def r : Nat := {r}", f"def K : Nat := {d['K']}",
         f"def p : Nat := {d['p']}", f"def q : Nat := {d['q']}", f"def tail : Nat := {d['tail']}"]
    if side == "lower":
        L += [f"def lt : Nat := {d['l']}", f"def ut : Nat := {d['u']}", f"def Kmax : Nat := {KMAX}"]
    else:
        L += [f"def ut : Nat := {d['u']}"]
    L += [f"def vec : List Nat := {lst(d['v'])}", "",
          f"theorem vec_ok : vecOK vec {N} = true := by decide +kernel"]
    if side == "upper":
        L += [f"theorem tail_ok : tailU {m} {r} {d['K']} {d['p']} {d['q']} {SCALE} tail ut = true := by"
              " decide +kernel"]
    else:
        L += [f"theorem tail_ok : tailL {m} {r} {d['K']} Kmax {d['p']} {d['q']} {SCALE} tail lt ut"
              " = true := by decide +kernel"]
    L += ["", f"end {ns}"]
    (DST / f"{tag}.lean").write_text("\n".join(L) + "\n", encoding="utf-8")
    for c in range(N // CH):
        js = range(CH * c, CH * c + CH)
        L = [hdr, f"import EpiFormal.ResidueCertGen.{tag}", "", "set_option maxRecDepth 100000", "",
             f"namespace {ns}", "open ResidueCertGen", ""]
        L += [f"def c{j} : List Nat := {lst(d['coef'][j])}" for j in js]
        L += ["", f"def tab{c} : List (List Nat) := [{', '.join(f'c{j}' for j in js)}]", "",
              f"theorem tab{c}_length : tab{c}.length = {CH} := by decide +kernel",
              f"theorem ok{c} : {chk} {A} {CH * c} tab{c} = true := by decide +kernel", "",
              f"end {ns}"]
        (DST / f"{tag}C{c}.lean").write_text("\n".join(L) + "\n", encoding="utf-8")
    nc = N // CH
    L = [hdr] + [f"import EpiFormal.ResidueCertGen.{tag}C{c}" for c in range(nc)] + [
        "", f"namespace {ns}", "open ResidueCertGen", "",
        "def tab : Nat → List (List Nat)"] + [f"  | {c} => tab{c}" for c in range(nc)] + [
        "  | _ => []", "",
        f"theorem tab_length (c : Nat) (hc : c < {nc}) : (tab c).length = {CH} := by",
        "  match c, hc with"] + [f"  | {c}, _ => exact tab{c}_length" for c in range(nc)] + [
        "", f"theorem tab_ok (c : Nat) (hc : c < {nc}) : {chk} {A} ({CH} * c) (tab c) = true := by",
        "  match c, hc with"] + [f"  | {c}, _ => exact ok{c}" for c in range(nc)] + [
        "", f"end {ns}"]
    (DST / f"{tag}All.lean").write_text("\n".join(L) + "\n", encoding="utf-8")


def main():
    certs = json.loads((HERE / "residue_certificate_general_N512.json").read_text())["certificates"]
    want = set(sys.argv[1:])
    for e in certs:
        m, r = e["modulus"], e["residue"]
        for side, key in (("lower", "L"), ("upper", "U")):
            tag = f"M{m}R{r}{key}"
            if want and tag not in want:
                continue
            s = Fraction(e[side])
            d = build(m, r, side, s)
            emit(tag, m, r, side, s, d)
            print(f"{tag}: s={s} K={d['K']} 2s={d['p']}/{d['q']} min margin={float(d['margin']):.6e}"
                  " python mirror OK, emitted", flush=True)



def emit_table():
    """Write EpiFormal/ResidueCertTable.lean: the 20 instances + Table brackets + separations."""
    certs = json.loads((HERE / "residue_certificate_general_N512.json").read_text())["certificates"]
    L = ["-- GENERATED by verification/emit_cert_gen.py (emit_table).",
         "import EpiFormal.ResidueCertGenSound"]
    L += [f"import EpiFormal.ResidueCertGen.M{e['modulus']}R{e['residue']}{k}All"
          for e in certs for k in "LU"]
    L += ["", "/-!", "# Kernel-checked brackets for `dimH F_{m,r}`, m ∈ {2,…,6}, r ∈ {1, m} (N = 512)",
          "", "Each bound instantiates `ResidueCertGen.dimH_le_of_certU` / `le_dimH_of_certL` with",
          "kernel-checked data. Brackets are closed: `lower ≤ dimH F_{m,r} ≤ upper`.", "-/", "",
          "namespace ResidueCertTable", "", "open ResidueCertGen ResidueModGeneral", ""]
    rows = []
    for e in certs:
        m, r = e["modulus"], e["residue"]
        lo, up = Fraction(e["lower"]), Fraction(e["upper"])
        for side, s in (("L", lo), ("U", up)):
            tag = f"M{m}R{r}{side}"
            K = (cert.first_tail_index(m, r))
            p, q = (2 * s).numerator, (2 * s).denominator
            ns = f"ResidueCertGen.{tag}"
            rowf = f"(fun j => ({ns}.tab (j / 64)).getD (j % 64) [])"
            chunks = (f"(fun j hj => rows_of_chunks{side} (C := 64) (nc := 8) {ns}.tab {ns}.tab_length"
                      f" {ns}.tab_ok j (by norm_num; exact hj))")
            if side == "U":
                L += [f"theorem dimH_F{m}{r}_le : dimH (residueConstSet {m} {r}) ≤ ENNReal.ofReal ({s.numerator} / {s.denominator} : ℝ) := by",
                      f"  have h := dimH_le_of_certU (m := {m}) (r := {r}) (K := {K}) (p := {p}) (q := {q})",
                      f"    (N := 512) (S := {SCALE}) (tail := {ns}.tail) (u := {ns}.ut) (vec := {ns}.vec)",
                      f"    {rowf}",
                      "    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)",
                      f"    (by norm_num) (by norm_num) {ns}.vec_ok {ns}.tail_ok",
                      f"    {chunks}"]
            else:
                L += [f"theorem le_dimH_F{m}{r} : ENNReal.ofReal ({s.numerator} / {s.denominator} : ℝ) ≤ dimH (residueConstSet {m} {r}) := by",
                      f"  have h := le_dimH_of_certL (m := {m}) (r := {r}) (K := {K}) (Kmax := {KMAX})",
                      f"    (p := {p}) (q := {q}) (N := 512) (S := {SCALE}) (tail := {ns}.tail) (l := {ns}.lt)",
                      f"    (u := {ns}.ut) (vec := {ns}.vec) {rowf}",
                      "    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)",
                      f"    (by norm_num) (by norm_num) (by norm_num) {ns}.vec_ok {ns}.tail_ok",
                      f"    {chunks}"]
            L += ["  convert h using 2", "  norm_num", ""]
        rows.append((m, r, lo, up))
    for m in range(2, 7):
        lo1 = next(lo for (mm, r, lo, up) in rows if mm == m and r == 1)
        upm = next(up for (mm, r, lo, up) in rows if mm == m and r == m)
        assert upm < lo1
        L += [f"/-- strict separation `dimH F_{{{m},{m}}} < dimH F_{{{m},1}}` "
              f"({upm} < {lo1}). -/",
              f"theorem dimH_F{m}{m}_lt_F{m}1 : dimH (residueConstSet {m} {m}) < dimH (residueConstSet {m} 1) :=",
              f"  (dimH_F{m}{m}_le).trans_lt <| lt_of_lt_of_le",
              f"    ((ENNReal.ofReal_lt_ofReal_iff (by norm_num)).mpr (by norm_num)) le_dimH_F{m}1", ""]
    L += ["end ResidueCertTable", ""]
    L += [f"#print axioms ResidueCertTable.{n}" for n in
          [f"dimH_F{m}{r}_le" for (m, r, _, _) in rows] + [f"le_dimH_F{m}{r}" for (m, r, _, _) in rows]
          + [f"dimH_F{m}{m}_lt_F{m}1" for m in range(2, 7)]]
    f = HERE.parent / "epi_formal" / "EpiFormal" / "ResidueCertTable.lean"
    f.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", f.name)


if __name__ == "__main__":
    if sys.argv[1:] == ["--table"]:
        emit_table()
    else:
        main()
        if not sys.argv[1:]:
            emit_table()
