"""Emitter v3 (2026-11-23): N=512 upper certificate (m=4, r=1, s=179/256) in CORE Lean.

Why v3 (diagnosis of chunk0 failure, see verification/cert_v3_redesign_20261123.md):
  * v2 `cert_h_hi_c*` quantified i over all of range 512 for every (j,k):
    512*130*512 ~ 3.4e7 `decide` cases (design said ~66k). Infeasible.
  * The provisional vector is NON-INCREASING (checked here, asserted), and every cell
    [l,r] has l <= r, so max(v[l..r]) = v[l]. Hence h_hi follows from antitonicity
    (511 comparisons) and maxV/cellL/cellR need not be stored at all:
    cell(a,e) = min(511, 512^2 // (a*512 + e)) is a closed formula, defined in Lean.
  * Only data kept: vector v (512 nats) and raw `hi` coefficients (rows x 130).
  * No `import Mathlib` (memory): pure core `List`/`Nat`, kernel GMP-accelerated ops.

Usage: python verification/emit_cert_core_v3.py <lo_row> <hi_row>
Writes epi_formal/EpiFormal/ResidueCertCoreV3_<lo>_<hi>_Draft.lean (NOT imported anywhere).
"""
import sys
from pathlib import Path

import residue_certificate_general_N512 as cert

LO = int(sys.argv[1]) if len(sys.argv) > 1 else 0
HI = int(sys.argv[2]) if len(sys.argv) > 2 else 8
M, R, S = 4, 1, cert.Fraction(179, 256)
rows, lower_tail, upper_tail, k_cut = cert.coefficients(M, R, S)
v = cert.provisional_vector(rows, (lower_tail + upper_tail) // 2)
N, SCALE, K = cert.GRID, cert.SCALE, k_cut
assert N == 512 and K == 130 and len(v) == N

# --- Python-side guarantees that justify dropping maxV / cellL / cellR -------------
assert all(v[i] >= v[i + 1] for i in range(N - 1)), "vector not antitone"
for j, row in enumerate(rows):
    for k, (_lo, _hi, left, right) in enumerate(row):
        a = M * k + R
        assert left == min(N - 1, N * N // (a * N + j + 1)) and right == cert.cell(a, j)
        assert left <= right and max(v[left:right + 1]) == v[left]

# --- Recompute the v2 margin with the v3 formula, must match certify_side exactly ---
def row_lhs(j):
    return sum(hi * v[min(N - 1, N * N // ((M * k + R) * N + j + 1))]
               for k, (_lo, hi, _l, _r) in enumerate(rows[j])) + upper_tail * v[0]

viol = [j for j in range(N) if not row_lhs(j) < SCALE * v[j]]
assert not viol, f"hcert fails at rows {viol[:5]}"
margin_v3 = min(cert.Fraction(SCALE * v[j] - row_lhs(j), SCALE * v[j]) for j in range(N))
margin_ref, _ = cert.certify_side(M, R, S, "upper")
assert margin_v3 == margin_ref, (margin_v3, margin_ref)
# --- E1 (unreduced form, what Lean checks): hi^128 * (a*512+j)^179 >= SCALE^128 * 512^179
C1 = SCALE**128 * N**179
for j, row in enumerate(rows):
    for k, (_lo, hi, _l, _r) in enumerate(row):
        assert hi**128 * ((M * k + R) * N + j)**179 >= C1, (j, k)
# --- tail: ustart >= SCALE*(4*129+1)^(-51/128), and tailU*4*(51/128) >= ustart
_, ustart = cert.enclose_power(cert.Fraction(M * (K - 1) + R), 2 * S - 1)
assert ustart**128 * (M * (K - 1) + R)**51 >= SCALE**128 and upper_tail * 4 * 51 >= ustart * 128
print(f"python check OK: 512/512 rows, min margin = {float(margin_v3):.6e} (== certify_side)")


def lst(xs):
    return "[" + ", ".join(str(int(x)) for x in xs) + "]"


out = [
    "/-",
    f"  ResidueCertCoreV3_{LO}_{HI}_Draft.lean -- GENERATED by verification/emit_cert_core_v3.py.",
    "  N=512, m=4, r=1, s=179/256, upper side. Rows [LO,HI). DRAFT: not imported by",
    "  EpiFormal.lean / Audit.lean. Pure core Lean (no Mathlib).",
    "-/",
    "",
    "set_option maxRecDepth 100000",
    "",
    "namespace ResidueCertV3",
    "",
    f"def vec : List Nat := {lst(v)}",
    "",
    "/-- left end of the image cell of grid cell `j` under digit `k` (a = 4k+1). -/",
    "def cellL (k j : Nat) : Nat := min 511 (512 * 512 / ((4 * k + 1) * 512 + j + 1))",
    "",
    "/-- `antiOK l` iff `l` is non-increasing. -/",
    "def antiOK : List Nat → Bool",
    "  | a :: b :: t => Nat.ble b a && antiOK (b :: t)",
    "  | _ => true",
    "",
    "/-- `Σ_{k} hi_k * vec[cellL k j]`, digits enumerated from `k`. -/",
    "def rowSum (j : Nat) : List Nat → Nat → Nat",
    "  | [], _ => 0",
    "  | h :: t, k => h * vec.getD (cellL k j) 0 + rowSum j t (k + 1)",
    "",
    f"def tailU : Nat := {upper_tail}",
    f"def SCALE : Nat := {SCALE}",
    "",
    "/-- row inequality of the upper certificate (strict). -/",
    "def rowOK (j : Nat) (hi : List Nat) : Bool :=",
    "  Nat.blt (rowSum j hi 0 + tailU * vec.getD 0 0) (SCALE * vec.getD j 0)",
    "",
    "/-- E1: every stored `hi` is an integer upper bound of SCALE*((a*512+j)/512)^(-179/128),",
    "    in the exponent-cleared form hi^128 * (a*512+j)^179 >= SCALE^128 * 512^179. -/",
    "def hiOK (j : Nat) : List Nat → Nat → Bool",
    "  | [], _ => true",
    "  | h :: t, k => Nat.ble (SCALE ^ 128 * 512 ^ 179) (h ^ 128 * ((4 * k + 1) * 512 + j) ^ 179)",
    "      && hiOK j t (k + 1)",
    "",
    f"def ustart : Nat := {ustart}",
    "/-- tail: ustart >= SCALE*517^(-51/128) and tailU >= ustart/(4*(51/128)). -/",
    "theorem tail_ok : Nat.ble (SCALE ^ 128) (ustart ^ 128 * 517 ^ 51) = true",
    "    ∧ Nat.ble (ustart * 128) (tailU * 4 * 51) = true := by decide +kernel",
    "",
    "theorem vec_length : vec.length = 512 := by decide +kernel",
    "theorem vec_anti : antiOK vec = true := by decide +kernel",
    "",
]
for j in range(LO, HI):
    out.append(f"def hi{j} : List Nat := {lst(hi for (_lo, hi, _l, _r) in rows[j])}")
    out.append(f"theorem row{j} : rowOK {j} hi{j} = true := by decide +kernel")
    out.append(f"theorem hiok{j} : hiOK {j} hi{j} 0 = true := by decide +kernel")
    out.append("")
out.append("end ResidueCertV3")
out.append("")
out.append("#print axioms ResidueCertV3.vec_anti")
out.append(f"#print axioms ResidueCertV3.row{LO}")
out.append(f"#print axioms ResidueCertV3.hiok{HI - 1}")
out.append("#print axioms ResidueCertV3.tail_ok")

dst = (Path(__file__).resolve().parent.parent / "epi_formal" / "EpiFormal"
       / f"ResidueCertCoreV3_{LO}_{HI}_Draft.lean")
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", dst.name, dst.stat().st_size, "bytes")
